const DICTS: Record<Lang, Dict> = { en, it };
const KEY = 'narwhal:lang';

function detect(): Lang {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === 'en' || saved === 'it') return saved;
  } catch {
    /* storage unavailable */
  }
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('it') ? 'it' : 'en';
}

export const i18n = $state({ lang: detect() });

export function setLang(lang: Lang) {
  i18n.lang = lang;
  try {
    localStorage.setItem(KEY, lang);
  } catch {
    /* storage unavailable */
  }
  document.documentElement.lang = lang;
}

/** Translate a key, replacing {name} placeholders with params. */
export function t(key: Key, params: Record<string, string | number> = {}): string {
  const s = DICTS[i18n.lang][key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m));
}

